#!/usr/bin/env python3
"""Write the harness's view of this repository's skills.

The Agent Skills under skills/<name>/SKILL.md stay the source, in the layout
cqframework/cqf-skills defines. The cat-harness knowledge graph reads one
package per directory, each with a package-manifest.json and one <name>.md per
skill. This script derives that view, under harness/skills/<plugin>/, from
skills/*/SKILL.md and the plugins in .claude-plugin/marketplace.json, so the
two cannot drift.

    python3 -I tools/kg-index/kg_index.py          # write
    python3 -I tools/kg-index/kg_index.py --check  # fail if anything is stale

Python 3.9+, standard library only. Deterministic: no network, no clock.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "harness" / "skills"
HEADER = "<!-- Generated by tools/kg-index/kg_index.py from skills/{name}/SKILL.md. Do not edit. -->"


def frontmatter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit("no frontmatter")
    fields, key = {}, None
    for line in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z_-]+):\s*(.*)$", line)
        if km:
            key, val = km.group(1), km.group(2).strip()
            fields[key] = "" if val in (">", "|", ">-", "|-") else val
        elif key and line.startswith((" ", "\t")):
            fields[key] = (fields[key] + " " + line.strip()).strip()
    return fields


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)


def build():
    market = json.loads((ROOT / ".claude-plugin" / "marketplace.json").read_text())
    files = {}
    placed = set()
    for plugin in market["plugins"]:
        src = plugin.get("source")
        if not isinstance(src, str):
            # A plugin maintained in its own repository: known, not held.
            continue
        slugs = []
        for p in plugin.get("skills", []):
            name = Path(p).name
            skill_md = ROOT / "skills" / name / "SKILL.md"
            fm = frontmatter(skill_md.read_text())
            if fm.get("name") != name:
                raise SystemExit(f"skills/{name}: frontmatter name is {fm.get('name')!r}")
            slugs.append(name)
            placed.add(name)
            body = "\n".join([
                "---",
                f"name: {name}",
                f"description: {yaml_str(fm.get('description', ''))}",
                f"license: {fm.get('license', 'Apache-2.0')}",
                f"source: skills/{name}/SKILL.md",
                f"plugin: {plugin['name']}",
                "---",
                HEADER.format(name=name),
                "",
                f"# {name}",
                "",
                fm.get("description", ""),
                "",
                f"The skill itself, with its resources, scripts and evals, is "
                f"[`skills/{name}/SKILL.md`](../../../skills/{name}/SKILL.md) "
                f"(evals: [`evals/{name}/`](../../../evals/{name}/)).",
                "",
            ])
            files[OUT / plugin["name"] / f"{name}.md"] = body
        manifest = {
            "name": plugin["name"],
            "version": market["metadata"]["version"],
            "description": plugin.get("description", ""),
            "skills": sorted(slugs),
        }
        files[OUT / plugin["name"] / "package-manifest.json"] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    on_disk = {p.parent.name for p in (ROOT / "skills").glob("*/SKILL.md")}
    missing = sorted(on_disk - placed)
    if missing:
        raise SystemExit("skills in no plugin of marketplace.json: " + ", ".join(missing))
    return files


def main():
    check = "--check" in sys.argv[1:]
    files = build()
    stale = []
    for path, text in sorted(files.items()):
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    extra = [p for p in OUT.rglob("*") if p.is_file() and p not in files] if OUT.exists() else []
    for p in extra:
        stale.append(p)
        if not check:
            p.unlink()
    rel = lambda p: p.relative_to(ROOT).as_posix()
    if check and stale:
        print("stale (run python3 -I tools/kg-index/kg_index.py):\n  " + "\n  ".join(map(rel, stale)))
        return 1
    print(f"{'checked' if check else 'wrote'} {len(files)} file(s); {len(stale)} {'stale' if check else 'changed'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
